import '../../services/telemetry_parser.dart';

/// Абстракція над BLE-з'єднанням зі станцією Anker.
///
/// Раніше вся ця логіка (connect/discoverServices/notify/keep-alive) жила
/// прямо всередині [AnkerBackgroundTaskHandler] разом зі звуком, порогами й
/// нотифікаціями — тому жоден сценарій оркестрації ("прийшла телеметрія ->
/// вирішити, чи дзвонити тривогу") не можна було перевірити без реального
/// BLE-стека. Інтерфейс дозволяє підмінити реальне з'єднання фейком у тестах.
abstract class AnkerConnection {
  /// Потік успішно розібраних пакетів телеметрії.
  Stream<TelemetryParseResult> get telemetry;

  /// `true`/`false` — реальні події підключення/розриву від BLE-стека
  /// (не невдалі спроби `connect`, ті обробляються мовчки й повторюються
  /// наступним тіком — так само, як і в попередній реалізації).
  Stream<bool> get connectionState;

  /// Чи є зараз активне з'єднання з пристроєм.
  bool get isConnected;

  /// Підключається до пристрою [deviceId] і підписується на телеметрію.
  /// Не робить нічого, якщо вже підключено чи підключення в процесі.
  Future<void> connect(String deviceId);

  /// Розриває поточне з'єднання (якщо є) і скидає внутрішній стан.
  Future<void> disconnect();

  /// Надсилає keep-alive пакет у характеристику запису. Якщо з'єднання
  /// нема — нічого не робить (виклик має вирішувати, чи перепідключатись).
  Future<void> sendKeepAlive();

  /// Остаточне звільнення ресурсів (закриває внутрішні стріми). Після
  /// цього об'єкт більше не можна використовувати.
  Future<void> dispose();
}
